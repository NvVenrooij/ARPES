import numpy as np
import torch
import matplotlib.pyplot as plt

class TightBinding:
    """
    Tight-binding model for calculating band structures and eigenvectors
    on user-defined k-space paths or planes.

    This class constructs the sp3s* Hamiltonian of the chosen material
    using Slater-Koster hopping parameters and, optionally, spin-orbit
    coupling. It then diagonalizes the Hamiltonian on the k-manifold
    generated by the Simulation object, yielding the band energies and
    corresponding eigenvectors used later in ARPES calculations.

    Main responsibilities
    ---------------------
    - read material-dependent tight-binding parameters,
    - compute direction cosines from the crystal structure,
    - construct the momentum-dependent Hamiltonian H(k),
    - diagonalize H(k) on a path or 2D plane in reciprocal space,
    - provide a canonical basis ordering that can also be reused by
      other classes, such as ARPES, when interpreting eigenvectors.

    Notes
    -----
    - In delta-layer mode, the tight-binding initial state is treated as
      strictly two-dimensional by fixing kz to a single reference value.
    - The Hamiltonian is written explicitly term by term so that the
      matrix structure remains transparent and easy to compare with
      derivations or literature.

    Canonical basis ordering used in this module
    --------------------------------------------
    The non-SOC sp3s* block occupies indices 0-9.
    If spin-orbit coupling is enabled, the spin-down block is appended
    at indices 10-19.

    sp3s*:
    0  A_s
    1  B_s
    2  A_px
    3  A_py
    4  A_pz
    5  B_px
    6  B_py
    7  B_pz
    8  A_s*
    9  B_s*

    sp3s* + SOC appended block:
    10 A_s_dn
    11 B_s_dn
    12 A_px_dn
    13 A_py_dn
    14 A_pz_dn
    15 B_px_dn
    16 B_py_dn
    17 B_pz_dn
    18 A_s*_dn
    19 B_s*_dn
    """

    def __init__(self, Material, Simulation, **kwargs):
        
        self.Material = Material
        self.Simulation = Simulation

        self.sc_params = self.calc_Slater_Koster_params()
        self.direction_cosines = self.calc_direction_cosines()
        self.bands, self.evecs = self.calculate_band_structure()
        self.basis_index_sp3s = {
                                    "A_s": 0,
                                    "B_s": 1,
                                    "A_px": 2,
                                    "A_py": 3,
                                    "A_pz": 4,
                                    "B_px": 5,
                                    "B_py": 6,
                                    "B_pz": 7,
                                    "A_sstar": 8,
                                    "B_sstar": 9,
                                }

        self.basis_index_sp3s_soc = {
                                        "A_s_dn": 10,
                                        "B_s_dn": 11,
                                        "A_px_dn": 12,
                                        "A_py_dn": 13,
                                        "A_pz_dn": 14,
                                        "B_px_dn": 15,
                                        "B_py_dn": 16,
                                        "B_pz_dn": 17,
                                        "A_sstar_dn": 18,
                                        "B_sstar_dn": 19,
                                    }
        
    def calc_Slater_Koster_params(self):

        v_ss = self.Material.material_parameters_AU['v_s-s']
        v_sa_pc = self.Material.material_parameters_AU['v_sa-pc']
        v_sc_pa = self.Material.material_parameters_AU['v_sc-pa']
        v_ssa_pc = self.Material.material_parameters_AU['v_ssa-pc']
        v_ssc_pa = self.Material.material_parameters_AU['v_ssc-pa']
        v_xx = self.Material.material_parameters_AU['v_x-x']
        v_xy = self.Material.material_parameters_AU['v_x-y']

        v_ss_110 = self.Material.material_parameters_AU['v_ss_110']
        v_sp_110 = self.Material.material_parameters_AU['v_sp_110']
        v_xx_110 = self.Material.material_parameters_AU['v_xx_110']
        v_xy_110 = self.Material.material_parameters_AU['v_xy_110']

        sc_params = {
        'v_s-s_sigma' : 0.25 * v_ss,
        'v_sa-pc_sigma' : np.sqrt(3) / 4 * v_sa_pc,
        'v_sc-pa_sigma' : np.sqrt(3) / 4 * v_sc_pa,
        'v_ssa-pc_sigma' : np.sqrt(3) / 4 * v_ssa_pc,
        'v_ssc-pa_sigma' : np.sqrt(3) / 4 * v_ssc_pa,
        'v_p-p_pi' : 0.25 * (v_xx - v_xy),
        'v_p-p_sigma' : 0.25 * (v_xx + 2 * v_xy),
        'v_s-s_sigma_NNN' : self.safe_compute(lambda x: (1/12) * x, v_ss_110),
        'v_s-p_sigma_NNN' : self.safe_compute(lambda x: (np.sqrt(2)/12) * x, v_sp_110),
        'v_p-p_pi_NNN' : self.safe_compute(lambda x, y: (1/12) * (x - y), v_xx_110, v_xy_110),
        'v_p-p_sigma_NNN' : self.safe_compute(lambda x, y: (1/12) * (x + y), v_xx_110, v_xy_110)        
        }

        return sc_params


    def calc_direction_cosines(self):
        
        """
        Calculate the direction cosines between the central atom and its neighbors.

        Returns:
        - direction_cosines (dict): Dictionary with keys 'NN', 'NNN', etc., and values
        lists of direction cosines.
        """

        positions = self.Material.real_space_lattice
        nn_positions, nnn_positions = self.Material.neighbours

        # Find index of the central atom
        distances_to_origin = torch.norm(positions, dim=1)
        index_of_origin = torch.argmin(distances_to_origin).item()
        central_position = positions[index_of_origin]

        direction_cosines = {'NN': [], 'NNN': []}

        # Compute direction cosines for NNs
        for pos in nn_positions:
            d = pos - central_position
            d_norm = torch.norm(d)
            l, m, n = (d / d_norm).tolist()
            direction_cosines['NN'].append((l, m, n))

        # Compute direction cosines for NNNs
        for pos in nnn_positions:
            d = pos - central_position
            d_norm = torch.norm(d)
            l, m, n = (d / d_norm).tolist()
            direction_cosines['NNN'].append((l, m, n))

        return direction_cosines


    def sp3s(self, spin_orbit = True, k_manifold= None):
        """
        Constructs the tight-binding Hamiltonian matrix including NNN interactions.

        Returns:
        - H (torch.Tensor): The Hamiltonian tensor of shape (..., 8, 8) or (..., 10, 10).
        """
        # Unpack parameters
        e_sa = self.Material.material_parameters_AU['e_sa']
        e_sc = self.Material.material_parameters_AU['e_sc']
        e_pa = self.Material.material_parameters_AU['e_pa']
        e_pc = self.Material.material_parameters_AU['e_pc']
        e_ssa = self.Material.material_parameters_AU['e_ssa']
        e_ssc = self.Material.material_parameters_AU['e_ssc']
        v_ss_sigma = self.sc_params['v_s-s_sigma']
        v_sa_pc_sigma = self.sc_params['v_sa-pc_sigma']
        v_sc_pa_sigma = self.sc_params['v_sc-pa_sigma']
        v_ssa_pc_sigma = self.sc_params['v_ssa-pc_sigma']
        v_ssc_pa_sigma = self.sc_params['v_ssc-pa_sigma']
        v_pp_sigma = self.sc_params['v_p-p_sigma']
        v_pp_pi = self.sc_params['v_p-p_pi']
        delta_potential = self.Simulation.simulation_input['delta_potential']/ 27.2113862459

        if spin_orbit:
            lambda_so_a = self.Material.material_parameters_AU['lambda_so_a'] / 3
            lambda_so_c = self.Material.material_parameters_AU['lambda_so_c'] / 3

        k_target = (
            self.Simulation.simulation_input['kz_shift']
            * 2 * np.pi
            / self.Material.material_parameters_AU['lattice_constant']
        )

        # Always start from a CLONE so we never modify Simulation.k_manifold in-place
        if k_manifold is None:
            k_manifold = self.Simulation.k_manifold.clone()

        if self.Simulation.simulation_input.get('delta_layer', False):
            # Force a single kz reference for the TB initial state (strict 2D)
            k_manifold[..., 2] = k_target

        # dtype + shape
        k_manifold = k_manifold.to(torch.float64)
        shape = k_manifold.shape[:-1]

        # Get direction cosines and neighbor positions for nearest neighbors
        direction_cosines_NN = self.direction_cosines['NN']  # List of (l, m, n)
        NN_positions, NNN_positions = self.Material.neighbours  # List of R vectors
        num_NN = len(direction_cosines_NN)

        # Initialize Hamiltonian tensor

        dimension = 10   # Shape: (..., 10, 10)
        diagonal = [e_sa, e_sc, e_pa, e_pa, e_pa + delta_potential , e_pc, e_pc, e_pc + delta_potential, e_ssa, e_ssc]
        if spin_orbit :
            dimension *= 2  # Shape: (..., 20, 20)
            diagonal *= 2 

        H = torch.zeros(shape + (dimension, dimension), dtype=torch.complex128) 
        # Assign on-site energies directly using indexing
        indices = torch.arange(dimension)
        # Create a mask for batch dimensions
        batch_indices = [slice(None)] * len(shape)
        # Now assign on-site energies
        H[batch_indices + [indices, indices]] = torch.tensor(
            diagonal, dtype=H.dtype, device=H.device
        )

        if spin_orbit :

            H[..., 2, 3] +=     lambda_so_a * -1j #X^Y^
            H[..., 12, 13] +=   lambda_so_a * 1j  #XvYv
            H[..., 4, 12] +=    lambda_so_a * -1  #Z^Xv
            H[..., 14, 2] +=    lambda_so_a       #ZvX^
            H[..., 3, 14] +=    lambda_so_a * -1j #Y^Zv
            H[..., 13, 4] +=    lambda_so_a * -1j #YvZ^

            H[..., 5, 6] +=     lambda_so_c * -1j 
            H[..., 15, 16] +=   lambda_so_c * 1j
            H[..., 7, 15] +=    lambda_so_c * -1
            H[..., 17, 5] +=    lambda_so_c 
            H[..., 6, 17] +=    lambda_so_c * -1j
            H[..., 16, 7] +=    lambda_so_c * -1j


        # Hopping terms for nearest neighbor interactions
        for i in range(num_NN):
            l, m, n = direction_cosines_NN[i]
            R = NN_positions[i]

            # Compute k_dot_R using einsum
            k_dot_R = torch.einsum('...i,i->...', k_manifold, R)  # Shape: (...)

            # Compute phase factors
            phase_factor = torch.exp(1j * k_dot_R)  # Shape: (...)

            # Hopping terms (broadcasting over leading dimensions)
            H[..., 0, 1] += v_ss_sigma * phase_factor
            
            # s-p hopping
            H[..., 0, 5] += v_sa_pc_sigma * l * phase_factor
            H[..., 0, 6] += v_sa_pc_sigma * m * phase_factor
            H[..., 0, 7] += v_sa_pc_sigma * n * phase_factor
            H[..., 8, 5] += v_ssa_pc_sigma * l * phase_factor
            H[..., 8, 6] += v_ssa_pc_sigma * m * phase_factor
            H[..., 8, 7] += v_ssa_pc_sigma * n * phase_factor

            # p-s hopping
            H[..., 2, 1] += -v_sc_pa_sigma * l * phase_factor
            H[..., 3, 1] += -v_sc_pa_sigma * m * phase_factor
            H[..., 4, 1] += -v_sc_pa_sigma * n * phase_factor
            H[..., 2, 9] += -v_ssc_pa_sigma * l * phase_factor
            H[..., 3, 9] += -v_ssc_pa_sigma * m * phase_factor
            H[..., 4, 9] += -v_ssc_pa_sigma * n * phase_factor

            # p-p hopping
            l2, m2, n2 = l**2, m**2, n**2
            lm, ln, mn = l * m, l * n, m * n

            # X1-X2, Y1-Y2, Z1-Z2
            H[..., 2, 5] += (v_pp_sigma * l2 + v_pp_pi * (1 - l2)) * phase_factor
            H[..., 3, 6] += (v_pp_sigma * m2 + v_pp_pi * (1 - m2)) * phase_factor
            H[..., 4, 7] += (v_pp_sigma * n2 + v_pp_pi * (1 - n2)) * phase_factor

            # Off-diagonal elements
            H[..., 2, 6] += (v_pp_sigma * lm + v_pp_pi * (-lm)) * phase_factor
            H[..., 2, 7] += (v_pp_sigma * ln + v_pp_pi * (-ln)) * phase_factor
            H[..., 3, 5] += (v_pp_sigma * lm + v_pp_pi * (-lm)) * phase_factor
            H[..., 3, 7] += (v_pp_sigma * mn + v_pp_pi * (-mn)) * phase_factor
            H[..., 4, 5] += (v_pp_sigma * ln + v_pp_pi * (-ln)) * phase_factor
            H[..., 4, 6] += (v_pp_sigma * mn + v_pp_pi * (-mn)) * phase_factor

            if spin_orbit :

                # Hopping terms (broadcasting over leading dimensions)
                H[..., 10, 11] += v_ss_sigma * phase_factor
                
                # s-p hopping
                H[..., 10, 15] += v_sa_pc_sigma * l * phase_factor
                H[..., 10, 16] += v_sa_pc_sigma * m * phase_factor
                H[..., 10, 17] += v_sa_pc_sigma * n * phase_factor
                H[..., 18, 15] += v_ssa_pc_sigma * l * phase_factor
                H[..., 18, 16] += v_ssa_pc_sigma * m * phase_factor
                H[..., 18, 17] += v_ssa_pc_sigma * n * phase_factor

                # p-s hopping
                H[..., 12, 11] += -v_sc_pa_sigma * l * phase_factor
                H[..., 13, 11] += -v_sc_pa_sigma * m * phase_factor
                H[..., 14, 11] += -v_sc_pa_sigma * n * phase_factor
                H[..., 12, 19] += -v_ssc_pa_sigma * l * phase_factor
                H[..., 13, 19] += -v_ssc_pa_sigma * m * phase_factor
                H[..., 14, 19] += -v_ssc_pa_sigma * n * phase_factor

                # p-p hopping
                l2, m2, n2 = l**2, m**2, n**2
                lm, ln, mn = l * m, l * n, m * n

                # As a reminder:
                #[1_s^, 2_s^, 1_px^, 1_py^, 1_pz^, 2_px^, 2_py^, 2_pz^, 1_ss^, 2_ss^,
                # 1_sv, 2_sv, 1_pxv, 1_pyv, 1_pzv, 2_pxv, 2_pyv, 2_pzv, 1_ssv, 2_ssv]
                
                # X1-X2, Y1-Y2, Z1-Z2
                H[..., 12, 15] += (v_pp_sigma * l2 + v_pp_pi * (1 - l2)) * phase_factor
                H[..., 13, 16] += (v_pp_sigma * m2 + v_pp_pi * (1 - m2)) * phase_factor
                H[..., 14, 17] += (v_pp_sigma * n2 + v_pp_pi * (1 - n2)) * phase_factor

                # Off-diagonal elements
                H[..., 12, 16] += (v_pp_sigma * lm + v_pp_pi * (-lm)) * phase_factor
                H[..., 12, 17] += (v_pp_sigma * ln + v_pp_pi * (-ln)) * phase_factor
                H[..., 13, 15] += (v_pp_sigma * lm + v_pp_pi * (-lm)) * phase_factor
                H[..., 13, 17] += (v_pp_sigma * mn + v_pp_pi * (-mn)) * phase_factor
                H[..., 14, 15] += (v_pp_sigma * ln + v_pp_pi * (-ln)) * phase_factor
                H[..., 14, 16] += (v_pp_sigma * mn + v_pp_pi * (-mn)) * phase_factor

        # Enforce Hermiticity
        H = H + H.transpose(-2, -1).conj() - torch.diag_embed(H.diagonal(dim1=-2, dim2=-1))

        return H
        
    def calculate_band_structure(self):

        """Calculates the band structure along a path or plane in k_space.
        
            input:
                - k_vecs: a 3xN or 3xNxN tensor containing all k-space vectors on the 
                path
                - params: a dictionary containing the relevant parameters for the
                tight binding model
                
            output: 
                - BS: band structure (eigenvalues) at every k in k_vecs
                - evecs: Eigenvectors at every k in k_vecs"""


        spin_orbit = self.Simulation.simulation_input["spin_orbit"]

        matrix = self.sp3s(spin_orbit)

        bands, evecs = torch.linalg.eigh(matrix)
        return bands, evecs
    

    def plot_bands_along_path(self):

        # Assume self.bands has shape (N, num_bands) and self.Simulation.k_manifold has shape (N, 3)
        bands = self.bands * 27.211  # converting to eV
        k_points = self.Simulation.k_manifold  # (N, 3) array of k-points

        # Compute cumulative distance along the k-path.
        distances = np.zeros(len(k_points))
        for i in range(1, len(k_points)):
            distances[i] = distances[i-1] + np.linalg.norm(k_points[i] - k_points[i-1])

        # Define high-symmetry point indices and labels (adjust these to your path)
        high_sym_indices = [0, 39, 79, 89, 129]

        if not self.Simulation.simulation_input['delta_layer']:
            high_sym_labels  = ['L', 'G', 'X', 'U', 'G']

        else:
            high_sym_labels = []
            for index in high_sym_indices:
                high_sym_point = k_points[index, :]/(2*np.pi/self.Material.material_parameters_AU['lattice_constant'])
                annotation = f"({high_sym_point[0]:.2f},\n {high_sym_point[1]:.2f},\n {high_sym_point[2]:.2f})"
                high_sym_labels += [annotation]


        # Create the figure
        plt.figure(figsize=(8,6))
        num_bands = bands.shape[1]
        for b in range(num_bands):
            plt.plot(distances, bands[:, b], color='black', linewidth=1, zorder=1)
            
            # Find the minimum of the current band.
            band_energy = bands[:, b]
            min_index = np.argmin(band_energy)
            min_energy = band_energy[min_index]
            min_distance = distances[min_index]
            # Format the k-point as a tuple with two decimal places.
            min_k = k_points[min_index, :]/(2*np.pi/self.Material.material_parameters_AU['lattice_constant'])  # This is a tensor with shape (3,)
            annotation = f"{min_energy:.2f} eV\n({min_k[0]:.2f}, {min_k[1]:.2f}, {min_k[2]:.2f})"

            # Highlight the minimum point with a red marker.
            plt.scatter(min_distance, min_energy, color='red', zorder=2)

            # Annotate the minimum with its energy and k-path coordinate.
            plt.annotate(annotation,
                        (min_distance, min_energy),
                        textcoords="offset points", 
                        xytext=(0,10),
                        ha='center',
                        fontsize=9,
                        color='red')

        # Set x-axis ticks at the high-symmetry points.
        tick_positions = [distances[i] for i in high_sym_indices]
        plt.xticks(tick_positions, high_sym_labels, fontsize=12)
        
        plt.xlabel("k-path", fontsize=14)
        plt.ylabel("Energy (eV)", fontsize=14)
        plt.title("Bandstructure along High-Symmetry Path", fontsize=16)
        plt.grid(True, which='both', linestyle='--', alpha=0.5)
        plt.show()

    @staticmethod
    def safe_compute(func, *args):
        if any(arg is None for arg in args):
            return None
        else:
            return func(*args)
        
    @staticmethod
    def polygon_mask(points, polygon):
        """
        Generate a boolean mask for points inside the polygon.
        points: (N, 2) tensor, polygon: (M, 2) tensor
        Returns: mask (N,) boolean tensor
        """
        N = points.shape[0]
        M = polygon.shape[0]

        # Repeat first vertex to close polygon
        polygon = torch.cat([polygon, polygon[:1]], dim=0)

        x, y = points[:,0], points[:,1]

        mask = torch.zeros(N, dtype=torch.bool)

        for i in range(M):
            x0, _, y0 = polygon[i]
            x1, _, y1 = polygon[i + 1]

            cond = ((y0 <= y) & (y < y1)) | ((y1 <= y) & (y < y0))
            intersection_x = (x1 - x0) * (y - y0) / (y1 - y0 + 1e-12) + x0

            mask ^= cond & (x < intersection_x)

        return mask
            

